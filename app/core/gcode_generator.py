"""Independent G-code generation engine with Bambu Lab A1 Mini compatibility layer."""

from __future__ import annotations

from datetime import datetime
from typing import Optional

from app import __app_name__, __version__
from app.core.models import (
    MovementType,
    ToolpathMove,
    ToolpathStats,
    WorkflowMode,
)
from app.machine.a1_mini import MachineProfile
from app.machine.profiles import PenProfile


class GcodeGenerator:
    """Generates readable, commented, absolute-coordinate G-code for pen plotting."""

    def __init__(
        self,
        machine: MachineProfile,
        pen: PenProfile,
        workflow_mode: WorkflowMode = WorkflowMode.BAMBU_SD_DIRECT,
        custom_start_gcode: Optional[str] = None,
        custom_end_gcode: Optional[str] = None,
    ) -> None:
        self.machine = machine
        self.pen = pen
        self.workflow_mode = workflow_mode
        self.custom_start_gcode = custom_start_gcode
        self.custom_end_gcode = custom_end_gcode

    def generate(
        self,
        moves: list[ToolpathMove],
        stats: Optional[ToolpathStats] = None,
        project_name: str = "Untitled Plot",
    ) -> str:
        """Generates complete G-code program and populates `gcode_line_number` and `gcode_command` on each `ToolpathMove`."""
        lines: list[str] = []

        # 1. Header metadata block (compatible with Bambu Studio / SD preview parsers)
        now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        est_sec = int(round(stats.estimated_time_seconds)) if stats else 0
        mins, secs = divmod(est_sec, 60)

        lines.append("; HEADER_BLOCK_START")
        lines.append(f"; Generated by: {__app_name__} v{__version__}")
        lines.append(f"; Timestamp: {now_str}")
        lines.append(f"; Project: {project_name}")
        lines.append(f"; Target Machine: {self.machine.name} ({self.machine.nominal_x_mm:.0f}x{self.machine.nominal_y_mm:.0f} mm)")
        lines.append(f"; Workflow Compatibility Mode: {self.workflow_mode.value}")
        lines.append(f"; Pen Profile: {self.pen.name} (Tip: {self.pen.tip_diameter_mm:.2f} mm, Calibrated: {self.pen.is_calibrated})")
        lines.append(f"; Z Heights: Draw={self.pen.drawing_z_mm:.2f} mm | Pen-Up={self.pen.pen_up_z_mm:.2f} mm | Safe={self.machine.safe_z_mm:.2f} mm")
        if stats:
            lines.append(
                f"; Drawing Bounds: X[{stats.min_x:.2f}..{stats.max_x:.2f}] Y[{stats.min_y:.2f}..{stats.max_y:.2f}] "
                f"({stats.drawing_width_mm:.2f} x {stats.drawing_height_mm:.2f} mm)"
            )
            lines.append(
                f"; Paths: {stats.num_paths} | Moves: {stats.num_movements} | "
                f"Draw Dist: {stats.drawing_distance_mm:.1f} mm | Travel Dist: {stats.travel_distance_mm:.1f} mm"
            )
            lines.append(f"; model printing time: {mins}m {secs}s; total estimated time: {mins}m {secs}s")
        lines.append("; HEADER_BLOCK_END")
        lines.append("")

        # 2. Workflow-specific compatibility instructions
        if self.workflow_mode == WorkflowMode.STANDARD_GCODE:
            lines.append("; [WORKFLOW: STANDARD GENERIC PLOTTER G-CODE]")
            lines.append("; Standard G21/G90/G0/G1 trajectory without machine-specific homing macros.")
        elif self.workflow_mode == WorkflowMode.BAMBU_SD_DIRECT:
            lines.append("; [WORKFLOW: BAMBU LAB A1 MINI - DIRECT MICRO-SD EXECUTION]")
            lines.append("; Copy this .gcode file to the ROOT directory of the A1 Mini MicroSD card.")
            lines.append("; Cold-plotting mode enforced (M104 S0 / M140 S0). No nozzle wipe or vibration test.")
        elif self.workflow_mode == WorkflowMode.BAMBU_STUDIO_3MF:
            lines.append("; [WORKFLOW: BAMBU STUDIO .GCODE.3MF CONTAINER]")
            lines.append("; Packaged for inspection and wireless dispatch via Bambu Studio.")
        lines.append("")

        # 3. Startup G-code sequence
        safe_z = max(self.machine.safe_z_mm, self.pen.pen_up_z_mm)
        z_feed = self.pen.z_speed_mm_s * 60.0
        travel_feed = self.pen.travel_speed_mm_s * 60.0

        if self.custom_start_gcode is not None and self.custom_start_gcode.strip():
            start_tpl = self.custom_start_gcode
        elif self.workflow_mode == WorkflowMode.STANDARD_GCODE:
            start_tpl = self.machine.start_gcode_standard
        else:
            start_tpl = self.machine.start_gcode_bambu_sd

        formatted_start = self._format_template(
            start_tpl,
            safe_z=safe_z,
            pen_up_z=self.pen.pen_up_z_mm,
            draw_z=self.pen.drawing_z_mm,
            z_feed=z_feed,
            travel_feed=travel_feed,
            park_x=self.machine.park_x_mm,
            park_y=self.machine.park_y_mm,
        )
        lines.append("; --- STARTUP SEQUENCE ---")
        for s_line in formatted_start.strip().splitlines():
            lines.append(s_line.rstrip())
        lines.append("")

        # Ensure G21 and G90 are always present
        joined_upper = "\n".join(lines).upper()
        if "G21" not in joined_upper:
            lines.append("G21 ; Millimeter units")
        if "G90" not in joined_upper:
            lines.append("G90 ; Absolute coordinates")

        # 4. Toolpath Body
        lines.append("; --- TOOLPATH MOVEMENTS ---")
        current_path_idx = -1

        for mv in moves:
            if mv.path_index != current_path_idx:
                current_path_idx = mv.path_index
                lines.append(f"; --- Path #{current_path_idx + 1} (Layer: {mv.layer}, Element: {mv.element_id}) ---")

            if mv.move_type == MovementType.TRAVEL:
                cmd_str = (
                    f"G0 X{mv.end_x:.3f} Y{mv.end_y:.3f} Z{mv.end_z:.3f} "
                    f"F{mv.feed_rate_mm_min:.0f} ; Travel (Pen Up)"
                )
                lines.append(cmd_str)
                mv.gcode_line_number = len(lines)
                mv.gcode_command = cmd_str

            elif mv.move_type == MovementType.PEN_DOWN:
                cmd_str = f"G1 Z{mv.end_z:.3f} F{mv.feed_rate_mm_min:.0f} ; Pen Down (Contact Z)"
                lines.append(cmd_str)
                mv.gcode_line_number = len(lines)
                mv.gcode_command = cmd_str
                if mv.dwell_ms > 0:
                    lines.append(f"G4 P{mv.dwell_ms} ; Pen stabilization dwell ({mv.dwell_ms} ms)")

            elif mv.move_type == MovementType.DRAW:
                cmd_str = (
                    f"G1 X{mv.end_x:.3f} Y{mv.end_y:.3f} "
                    f"F{mv.feed_rate_mm_min:.0f} ; Draw"
                )
                lines.append(cmd_str)
                mv.gcode_line_number = len(lines)
                mv.gcode_command = cmd_str

            elif mv.move_type == MovementType.PEN_UP:
                cmd_str = f"G0 Z{mv.end_z:.3f} F{mv.feed_rate_mm_min:.0f} ; Pen Up (Lift Z)"
                lines.append(cmd_str)
                mv.gcode_line_number = len(lines)
                mv.gcode_command = cmd_str

        lines.append("")

        # 5. Ending G-code sequence
        if self.custom_end_gcode is not None and self.custom_end_gcode.strip():
            end_tpl = self.custom_end_gcode
        elif self.workflow_mode == WorkflowMode.STANDARD_GCODE:
            end_tpl = self.machine.end_gcode_standard
        else:
            end_tpl = self.machine.end_gcode_bambu_sd

        formatted_end = self._format_template(
            end_tpl,
            safe_z=safe_z,
            pen_up_z=self.pen.pen_up_z_mm,
            draw_z=self.pen.drawing_z_mm,
            z_feed=z_feed,
            travel_feed=travel_feed,
            park_x=self.machine.park_x_mm,
            park_y=self.machine.park_y_mm,
        )
        lines.append("; --- ENDING SEQUENCE ---")
        for e_line in formatted_end.strip().splitlines():
            lines.append(e_line.rstrip())
        lines.append("; --- END OF FILE ---")

        return "\n".join(lines) + "\n"

    @staticmethod
    def _format_template(template: str, **kwargs: float) -> str:
        try:
            return template.format(**kwargs)
        except Exception:
            return template
